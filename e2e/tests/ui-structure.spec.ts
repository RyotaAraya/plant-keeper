import { test, expect, login, ACCOUNTS, openPlans } from './support'

test('安全の確認を承認待ちより先に表示し、省略した承認待ちも展開・印刷できる', async ({ page }) => {
  await login(page, ACCOUNTS.admin)
  const approvals = page.getByTestId('home-approvals')
  await expect(approvals.getByRole('list')).toBeVisible()
  const order = await page.locator('[data-testid="home-bypasses"], [data-testid="home-urgent"], [data-testid="home-approvals"]').evaluateAll(els => els.map(el => el.getAttribute('data-testid')))
  expect(order[0]).toBe('home-bypasses')
  expect(order.at(-1)).toBe('home-approvals')
  const count = await approvals.locator('li').count()
  expect(count).toBeGreaterThan(3)
  await expect(approvals.locator('li:visible')).toHaveCount(3)
  await approvals.getByRole('button', { name: /承認待ちをすべて見る/ }).click()
  await expect(approvals.locator('li:visible')).toHaveCount(count)
  await approvals.getByRole('button', { name: '表示を減らす' }).click()
  await page.emulateMedia({ media: 'print' })
  await expect(approvals.locator('li:visible')).toHaveCount(count)
})

for (const width of [1440, 390]) {
  test(`${width}pxで記録の見方を切り替え、下書きの再開と承認待ちの絞り込みが使える`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    await login(page, ACCOUNTS.admin)
    await page.goto('/inspections')
    await expect(page.getByRole('table')).toBeVisible()
    await expect(page.getByTestId('inspection-drafts')).toHaveCount(0)
    await page.getByRole('button', { name: '自分の下書き', exact: true }).click()
    await expect(page).toHaveURL(/view=drafts/)
    await expect(page.getByTestId('inspection-drafts')).toBeVisible()
    await expect(page.getByRole('table')).toHaveCount(0)
    await page.reload()
    await expect(page.getByTestId('inspection-drafts')).toBeVisible()
    const response = page.waitForResponse(res => res.url().includes('/api/v1/inspections?') && new URL(res.url()).searchParams.get('status') === 'approval_requested')
    await page.getByRole('button', { name: '承認待ち', exact: true }).click()
    const records = (await (await response).json()).data
    expect(records.length).toBeGreaterThan(0)
    expect(records.every((record: { status: string }) => record.status === 'approval_requested')).toBe(true)
    await expect(page.getByRole('table')).toBeVisible()
    await expect(page.getByTestId('inspection-drafts')).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  })
}

test('計画の種類と見方を切り替えても全拠点の選択を保持する', async ({ page }) => {
  await login(page, ACCOUNTS.admin)
  await openPlans(page)
  await expect(page.getByTestId('plan-groups')).toBeVisible()
  await expect(page.getByTestId('plan-maintenances')).toHaveCount(0)
  await page.getByRole('button', { name: '表示する拠点を選ぶ' }).click()
  await page.getByRole('button', { name: '全拠点', exact: true }).click()
  await page.getByRole('button', { name: '点検の期限順', exact: true }).click()
  await expect(page.getByRole('button', { name: '表示する拠点を選ぶ' })).toContainText('全拠点')
  await page.getByRole('button', { name: '定期整備', exact: true }).click()
  await expect(page.getByTestId('plan-maintenances')).toBeVisible()
  await expect(page.getByRole('button', { name: '表示する拠点を選ぶ' })).toContainText('全拠点')
})

test('組織のメニューを開いて管理画面へ移ると現在の場所が見える', async ({ page }) => {
  await login(page, ACCOUNTS.admin)
  const toggle = page.getByRole('button', { name: '組織と設定', exact: true })
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('link', { name: '監査ログ', exact: true })).toBeHidden()
  await toggle.click()
  await page.getByRole('link', { name: '監査ログ', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: '監査ログ' })).toBeVisible()
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await page.reload()
  await expect(page.getByRole('link', { name: '監査ログ', exact: true })).toBeVisible()
})
